// app/api/squad/export/route.ts
// Deterministic export template for group-chat invite with Blind Cap privacy protection.

import { NextRequest, NextResponse } from 'next/server';

export const runtime = 'nodejs';

export async function POST(req: NextRequest) {
  try {
    const { plan, timeWindow } = await req.json();

    const venue = plan?.primaryVenue || { name: 'Third Place Venue', address: 'Chicago, IL', neighborhood: 'Chicago' };
    const ledger = plan?.ledger || {};
    const culturalDna = plan?.culturalDna;

    const windowText = timeWindow
      ? `${(timeWindow.day || 'Weekend').toUpperCase()} ${timeWindow.start || ''}-${timeWindow.end || ''}`
      : 'This Weekend';

    const sharedTagsText =
      culturalDna?.sharedTags?.slice(0, 3).map((t: any) => t.name).join(', ') || 'Shared squad vibes';

    const members = ledger.memberLedgers || ledger.memberRows || [];
    const maxSpend = members.length > 0
      ? Math.max(...members.map((m: any) => m.LI09_TotalPerPersonAllInCents || 0))
      : 1500;

    const neighborhood = (venue.neighborhood || 'chicago').replace(/_/g, ' ').toUpperCase();
    const sourceUrl = venue.source?.url || 'Verified Chicago Catalog';

    const inviteText = `✨ ThirdPlace Squad Plan: ${venue.name}
📍 ${venue.address} (${neighborhood})
⏰ Window: ${windowText}
🎯 Cultural Match: ${sharedTagsText} (via Qloo)

💰 All-In Cost Breakdown (13-Row Pre-Spend Split):
• Estimated Spend: $${(maxSpend / 100).toFixed(2)} per person (includes tax, tip, commute, & contingency)
• Budget Protection: Blind Cap Mode active (no friend singled out)
• Pricing: Sourced from verified catalog (${sourceUrl})

"Estimates only; check prices before you go."
Generated by ThirdPlace Squad | Qloo Agentic Hackathon 2026`;

    return NextResponse.json({ inviteText });
  } catch (err: any) {
    return NextResponse.json({ error: err.message }, { status: 500 });
  }
}
